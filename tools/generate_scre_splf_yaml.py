"""Generate explicit, separate RT-DETR-R18 SCRE/SPLF ablation YAML files."""

from copy import deepcopy
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "ultralytics" / "cfg" / "models" / "rt-detr"
BASELINE = yaml.safe_load((DIRECTORY / "rtdetr-r18.yaml").read_text(encoding="utf-8"))
BACKBONE_COUNT = len(BASELINE["backbone"])
BASE_DECODER = BASELINE["head"][-1]


def shift_from(source):
    """Shift absolute head references after inserting the SCRE side path."""
    if isinstance(source, list):
        return [shift_from(item) for item in source]
    return source + 1 if source >= BACKBONE_COUNT else source


def make(variant):
    config = deepcopy(BASELINE)
    config["nc"] = 1
    config["scre_splf"] = {
        "variant": variant,
        "small_max_px": 16.0,
        "lambda_center": 0.05,
        "lambda_offset": 0.10,
        "lambda_protect": 0.01,
    }
    original_neck = deepcopy(BASELINE["head"][:-1])
    original_f3, original_f4, original_f5 = BASE_DECODER[0]
    if variant != "splf":
        use_offset = variant != "scre_splf_no_offset"
        config["head"] = [[[4, 5], 1, "SCRE", [64, 32, 5, use_offset]]]
        for position, (source, repeat, module, arguments) in enumerate(original_neck):
            # The first ordinary neck layer must still read the original P5,
            # not the immediately preceding SCRE side-path tensor.
            config["head"].append([BACKBONE_COUNT - 1 if position == 0 else shift_from(source),
                                   repeat, module, arguments])
        fusion = "SCREFixedFusion" if variant == "scre" else "SPLF"
        args = [64, 0.05] if variant == "scre" else [64, 32, 0.1]
        scre_index = BACKBONE_COUNT
        fusion_index = BACKBONE_COUNT + len(config["head"])
        config["head"].append([[shift_from(original_f3), scre_index], 1, fusion, args])
        config["head"].append([[fusion_index, shift_from(original_f4), shift_from(original_f5)],
                               *BASE_DECODER[1:]])
    else:
        config["head"] = original_neck
        fusion_index = BACKBONE_COUNT + len(config["head"])
        config["head"].append([original_f3, 1, "SPLF", [64, 32, 0.1]])
        config["head"].append([[fusion_index, original_f4, original_f5], *BASE_DECODER[1:]])
        config["scre_splf"]["lambda_offset"] = 0.0
    if variant == "scre":
        config["scre_splf"]["lambda_protect"] = 0.0
    if variant == "scre_splf_no_offset":
        config["scre_splf"]["lambda_offset"] = 0.0
    if variant == "scre_splf_no_protect":
        config["scre_splf"]["lambda_protect"] = 0.0
    return config


def main():
    variants = ("scre", "splf", "scre_splf", "scre_splf_no_offset", "scre_splf_no_protect")
    for variant in variants:
        target = DIRECTORY / f"rtdetr_r18_{variant}.yaml"
        target.write_text("# Generated by tools/generate_scre_splf_yaml.py; do not edit by hand.\n" +
                          yaml.safe_dump(make(variant), sort_keys=False, allow_unicode=True), encoding="utf-8")
        print(target)


if __name__ == "__main__":
    main()
